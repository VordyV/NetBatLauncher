validate = b"\x28\x74\x53\x42\x4b\x40\x35\x5a"

def parse_gs_response(data: bytes | bytearray) -> dict[str, object]:
	data = bytes(data)
	result = {
		"format": None,
		"keys": [],
		"servers": []
	}

	if b"hostname" in data and b"gametype" in data:
		try:
			pos = 0
			length = len(data)

			while pos < length and not (data[pos:pos+8] == b"hostname"):
				pos += 1

			keys = []
			while pos < length - 2:
				end = data.find(b"\x00", pos)
				if end == -1:
					break

				key = data[pos:end].decode("ascii", errors="ignore").strip()
				if key:
					keys.append(key)

				pos = end + 1

				if pos < length and data[pos] == 0x00:
					pos += 1

				if pos < length and data[pos] == 0x72:
					break
				if pos < length and data[pos:pos+4] == b"\xff\xff\xff\xff":
					break

			result["keys"] = keys
			result["format"] = "full"

			if not keys:
				pass
			else:
				while pos < length - 10:
					if data[pos] == 0x72:
						pos += 1
						try:
							ip1 = str(ipaddress.IPv4Address(data[pos:pos+4]))
							port1 = struct.unpack(">H", data[pos+4:pos+6])[0]
							ip2 = str(ipaddress.IPv4Address(data[pos+6:pos+10]))
							port2 = struct.unpack(">H", data[pos+10:pos+12])[0]
							pos += 12

							server_data = {}
							for key in keys:
								if pos >= length:
									break

								if data[pos] == 0xff:
									pos += 1
									end = data.find(b"\x00", pos)
									if end == -1:
										break
									value = data[pos:end].decode("utf-8", errors="ignore")
									server_data[key] = value
									pos = end + 1
								else:
									break

							result["servers"].append({
								"ip": ip1,
								"port": port1,
								"ip2": ip2,
								"port2": port2,
								"data": server_data
							})
						except Exception:
							pos += 1
							continue

					elif data[pos:pos+4] == b"\xff\xff\xff\xff":
						break
					else:
						pos += 1

				return result

		except Exception:
			pass

	result["format"] = "compact"
	result["keys"] = []
	result["servers"] = []

	i = 0
	length = len(data)

	while i < length - 6:
		if data[i] == 0x11:
			try:
				ip_bytes = data[i+1:i+5]
				port_bytes = data[i+5:i+7]

				ip = str(ipaddress.IPv4Address(ip_bytes))
				port = struct.unpack(">H", port_bytes)[0]

				if 1 <= port <= 65535 and not ip.startswith("0."):
					result["servers"].append({
						"ip": ip,
						"port": port,
						"data": {}
					})
					i += 12
					continue
			except Exception:
				pass

		if data[i:i+4] == b"\xff\xff\xff\xff":
			break

		i += 1

	return result

async def get_server_list(host: str, port: int, key: str, timeout: float = 5.0):
	reader, writer = await asyncio.wait_for(
		asyncio.open_connection(host, port), timeout=timeout,
	)
	try:
		writer.write(bytes_to_send)
		await writer.drain()

		response = b""
		try:
			while True:
				chunk = await asyncio.wait_for(reader.read(4096), timeout=timeout)
				if not chunk:
					break
				response += chunk
		except asyncio.TimeoutError:
			pass

		decresult = await asyncio.to_thread(EncTypeX().decrypt, key.encode(), validate, bytearray(response))

		return await asyncio.to_thread(parse_gs_response, bytearray(decresult))
	finally:
		writer.close()
		try:
			await writer.wait_closed()
		except Exception:
			pass